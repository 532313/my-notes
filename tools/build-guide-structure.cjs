const fs=require('fs'),path=require('path');
const source=JSON.parse(fs.readFileSync(path.join(__dirname,'guide-source-headings.json'),'utf8'));
const runtime=String.raw`
(function(root){
 'use strict';
 const norm=s=>s.replace(/\s/g,'');
 function splitParagraph(p,titles){
  if(p.children.length||p.closest('[hidden]'))return;
  const text=p.textContent,flat=norm(text),offsets=[];for(let i=0;i<text.length;i++)if(!/\s/.test(text[i]))offsets.push(i);
  const hits=[];
  for(const title of titles){const key=norm(title);let at=flat.indexOf(key);if(at<0)continue;
   // A source line is a heading only when it ends at the paragraph boundary,
   // or precedes another sentence/field; never match a reference inside prose.
   const start=offsets[at],end=offsets[at+key.length-1]+1;
   if(start>0&&!/[。！？；：:]\s*$/.test(text.slice(0,start)))continue;
   if(end<text.length&&/^[\u4e00-\u9fffA-Za-z0-9_]/.test(text.slice(end)))continue;
   hits.push({start,end});
  }
  hits.sort((a,b)=>a.start-b.start);let cursor=0;const fragment=p.ownerDocument.createDocumentFragment();
  for(const hit of hits){if(hit.start<cursor)continue;if(hit.start>cursor){const before=p.cloneNode(false);before.textContent=text.slice(cursor,hit.start);fragment.append(before);}
   const heading=p.ownerDocument.createElement('h5');heading.className='body-subheading';heading.textContent=text.slice(hit.start,hit.end);fragment.append(heading);cursor=hit.end;}
  if(!hits.length)return;if(cursor<text.length){const after=p.cloneNode(false);after.textContent=text.slice(cursor);fragment.append(after);}p.replaceWith(fragment);
 }
 function format(container){
  for(const card of container.querySelectorAll('.page-card')){
   const area=card.querySelector('.page-content'),titles=MAP[card.dataset.page]||[];
   for(const p of [...area.querySelectorAll('p.body-copy')])splitParagraph(p,titles);
   const paragraphs=[...area.querySelectorAll('p.body-copy')];
   for(const p of paragraphs){
    if(!p.isConnected||p.dataset.structured||p.closest('[hidden]'))continue;
    const m=p.textContent.match(/^(函数原型|函数作用|函数功能|函数参数|函数返回值|返回值|参数说明|参数含义|功能描述)[：:]/);if(!m)continue;
    p.classList.add('api-field');p.dataset.structured='true';
    if(m[1]==='函数原型'){
     let balance=(p.textContent.match(/\(/g)||[]).length-(p.textContent.match(/\)/g)||[]).length;
     while(balance>0){const next=p.nextElementSibling;if(!next?.matches('p.body-copy')||/^(函数|参数|返回)/.test(next.textContent)||next.textContent.length>200)break;
      const span=p.ownerDocument.createElement('span');span.textContent=next.textContent;p.append(' ',span);balance+=(next.textContent.match(/\(/g)||[]).length-(next.textContent.match(/\)/g)||[]).length;next.remove();}
     p.classList.add('api-signature');
    }
    const text=p.textContent;p.replaceChildren();const label=p.ownerDocument.createElement('strong');label.textContent=m[0];p.append(label);
    const value=p.ownerDocument.createElement(m[1]==='函数原型'?'code':'span');value.textContent=text.slice(m[0].length);p.append(value);
    if(/参数/.test(m[1])){
     let next=p.nextElementSibling,list;
     while(next?.matches('p.body-copy')&&!next.classList.contains('api-field')&&/^(?:(?:const|struct|unsigned|signed|void|char|int|long|short|enum)\s|[A-Za-z_]\w*\s*[：:])/.test(next.textContent)&&/[：:]/.test(next.textContent)){
      if(!list){list=p.ownerDocument.createElement('ul');list.className='api-parameters';p.after(list);}const following=next.nextElementSibling,item=p.ownerDocument.createElement('li');while(next.firstChild)item.append(next.firstChild);list.append(item);next.remove();next=following;
     }
    }
   }
  }
 }
 root.HandbookStructure={format};
})(window);
`;
const output='// Source-verified heading lines from the original PDF; generated by tools/build-guide-structure.cjs.\nconst MAP='+JSON.stringify(source)+';\n'+runtime;
fs.writeFileSync('guide/3568阅读资源/body-structure.js',output);
